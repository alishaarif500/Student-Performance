class StudentGradePredictor:
    """
    A robust inference pipeline for predicting student final grades (G3).
    Includes input schema validation, runtime error handling, and bias disclaimers.
    """
    def __init__(self, model, preprocessor, subject="Math"):
        self.model = model
        self.preprocessor = preprocessor
        self.subject = subject
        self.disclaimer = (
            "[RESPONSIBLE AI DISCLAIMER] This tool predicts academic outcomes based on historical patterns "
            "associated with social and demographic variables. It must NEVER be used to penalize, select, "
            "or label students. Its primary objective is to highlight students who may benefit from "
            "proactive tutoring and early academic interventions."
        )

    def predict_grade(self, raw_input_dict):
        # 1. Input Validation
        required_features = ['age', 'Medu', 'Fedu', 'traveltime', 'studytime', 'failures',
                             'famrel', 'freetime', 'goout', 'Dalc', 'Walc', 'health', 'absences', 'G1', 'G2']

        for feature in required_features:
            if feature not in raw_input_dict:
                raise ValueError(f"Missing critical numerical feature for inference: '{feature}'")

        # 2. Check bounds for numeric inputs
        if not (0 <= raw_input_dict['G1'] <= 20) or not (0 <= raw_input_dict['G2'] <= 20):
            raise ValueError("Grades G1 and G2 must strictly reside between 0 and 20 (Portuguese standard scale).")

        # 3. Build DataFrame matching the exact structural format
        try:
            input_df = pd.DataFrame([raw_input_dict])
            # Ensure categorical columns not supplied in dict default to safe placeholders
            for col in cat_cols:
                if col not in input_df.columns:
                    input_df[col] = mat_df[col].mode()[0]  # Fallback to dataset mode

            # Ensure columns are ordered exactly as in original training sets
            input_df = input_df[mat_df.drop(columns=['G3']).columns]

            # 4. Transform inputs
            processed_input = self.preprocessor.transform(input_df)

            # 5. Predict outcome
            prediction = self.model.predict(processed_input)[0]

            # Bound predictions to actual academic grading range
            final_prediction = max(0.0, min(20.0, float(prediction)))

            return {
                "subject": self.subject,
                "predicted_G3": round(final_prediction, 2),
                "disclaimer": self.disclaimer
            }
        except Exception as e:
            return {
                "error": f"Prediction pipeline failed: {str(e)}"
            }

