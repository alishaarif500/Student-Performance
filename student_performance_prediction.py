from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler, OneHotEncoder
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline

# Ensure datasets are loaded globally
if 'mat_df' not in locals() or 'mat_df' not in globals():
    mat_df = pd.read_csv('data/student-mat.csv', sep=';')
if 'por_df' not in locals() or 'por_df' not in globals():
    por_df = pd.read_csv('data/student-por.csv', sep=';')

def preprocess_dataset(df, target='G3', test_size=0.2, random_state=42):
    # Separate features and target
    X = df.drop(columns=[target])
    y = df[target]

    # Categorical and numerical columns configuration
    numerical_cols = X.select_dtypes(include=['int64', 'float64']).columns.tolist()
    categorical_cols = X.select_dtypes(include=['object', 'category']).columns.tolist()

    # Pipeline elements: standard scaler for numerical, one-hot encoder for categorical attributes
    numerical_transformer = StandardScaler()
    categorical_transformer = OneHotEncoder(drop='first', handle_unknown='ignore')

    preprocessor = ColumnTransformer(
        transformers=[
            ('num', numerical_transformer, numerical_cols),
            ('cat', categorical_transformer, categorical_cols)
        ]
    )

    # Split data BEFORE scaling/encoding to avoid data leakage
    X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=test_size, random_state=random_state)

    # Fit and transform training set, transform testing set
    X_train_proc = preprocessor.fit_transform(X_train)
    X_test_proc = preprocessor.transform(X_test)

    # Get transformed column names for feature trackability
    cat_encoder = preprocessor.named_transformers_['cat']
    cat_encoded_cols = cat_encoder.get_feature_names_out(categorical_cols).tolist()
    feature_names = numerical_cols + cat_encoded_cols

    return X_train_proc, X_test_proc, y_train, y_test, feature_names, preprocessor

# Preprocess both student cohorts separately
X_train_mat, X_test_mat, y_train_mat, y_test_mat, feat_names_mat, preprocessor_mat = preprocess_dataset(mat_df)
